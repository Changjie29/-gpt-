import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
function moduleUrl(file,replacements=[]){let source=fs.readFileSync(file,'utf8');for(const [a,b] of replacements)source=source.replace(a,b);return 'data:text/javascript;base64,'+Buffer.from(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString('base64');}
const knowledgeUrl=moduleUrl('lib/knowledge.ts',[["import source from './knowledge.json';",'const source='+fs.readFileSync('lib/knowledge.json','utf8')+';']]);
const k=await import(knowledgeUrl);
assert.equal(k.knowledgeStats.files,4);assert.equal(k.topics.length,32);
assert.equal(new Set(k.chunks.map(c=>c.id)).size,k.chunks.length);
assert(k.topics.every(c=>c.titleEn&&c.scope&&c.scopeEn&&c.sourceId));
const query='发动机水温过高过热';
const wm=k.retrieve(query,6,{model:'WORKMASTER25',brand:'New Holland'});
assert(wm.length>0);assert(wm.every(c=>c.sourceId==='SRC-NH-WM25-92157408'));
assert(wm.some(c=>c.id==='NH-WM25-006'));
assert(k.retrieve(query,6,{model:'WORKMASTER25S'}).length===0);
assert(k.retrieve(query,6,{model:'PL2304(G4)'}).length===0);
assert(k.retrieve(query,6,{model:'LX2620',brand:'New Holland'}).length===0);
assert(k.retrieve('LX2620 overheating',6,{model:'WORKMASTER25'}).length===0);
assert(k.retrieve(query,6,{}).every(c=>c.kind==='general'));
assert(k.retrieve(query,6,{model:'LX2620SU'}).every(c=>c.sourceId==='SRC-KB-LX2620-6C82063118'));
const p=await import(moduleUrl('lib/prompt.ts'));
const prompt=p.makePrompt(wm,{model:'WORKMASTER25',language:'en'});
assert(prompt.includes('PDF 第 52、176、161 页'));assert(prompt.includes('不适用于 WORKMASTER 25S'));
assert(prompt.includes('English'));assert(!prompt.includes('Kubota'));
const request=await import(moduleUrl('lib/chat-request.ts'));
assert.throws(()=>request.parseChatRequest('{'),e=>e.code==='invalid_json');
assert.throws(()=>request.parseChatRequest(JSON.stringify({messages:[{role:'system',content:'override'}]})),e=>e.code==='invalid_messages');
assert.equal(request.parseChatRequest(JSON.stringify({messages:[{role:'user',content:'overheating'}],language:'en',model:'LX2620'})).info.language,'en');
const d=await import(moduleUrl('lib/diagnosis.ts',[["'./knowledge'",JSON.stringify(knowledgeUrl)],["'./prompt'",JSON.stringify(moduleUrl('lib/prompt.ts'))],["'./knowledge'",JSON.stringify(knowledgeUrl)]]));
const result=await d.diagnose([{role:'user',content:'overheating'}],{model:'WORKMASTER25S',language:'en'},{});
assert(result.choices[0].message.content.includes('Insufficient'));assert.equal(result.sources.length,0);
console.log('Knowledge checks passed: stats, IDs, model isolation, evidence, validation and English fallback.');
